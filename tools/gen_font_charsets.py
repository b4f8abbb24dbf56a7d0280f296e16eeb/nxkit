#!/usr/bin/env python3
"""Generate crates/nxb-font/data/charsets.txt: the character sets of the shared font stand-ins.
Usage: gen_font_charsets.py <out file>   (dev tool, output is committed, needs fontTools)

The sets are those of NX2Apple's dm/tools/make_shared_fonts.py (MIT, refer to THIRD_PARTY.md): every character of a
double-byte legacy set as Python's codecs decode it, plus a common part. The file also holds the bidi mirror pairs that
fontTools' subsetter adds to a cut (bidi_closure), limited to the characters of the sets, and the Unicode blocks of the
OS/2 ulUnicodeRange bits (OpenType specification 1.7, as fontTools lists them)."""
import sys
from fontTools.ttLib.tables.O_S_2f_2 import OS2_UNICODE_RANGES
from fontTools.unicodedata import mirrored


def rng(*pairs):
    return {c for a, b in pairs for c in range(a, b + 1)}


def legacy(codec, lead, trail=None):
    out, (lo, hi) = set(), trail or lead
    for a in range(lead[0], lead[1] + 1):
        for b in range(lo, hi + 1):
            try:
                s = bytes([a, b]).decode(codec)
            except UnicodeDecodeError:
                continue
            if len(s) == 1:
                out.add(ord(s))
    return out


COMMON = rng((0x20, 0x7e), (0xa0, 0xff), (0x2000, 0x206f), (0x3000, 0x303f), (0xff00, 0xffef))


def charsets():
    gb2312 = legacy('gb2312', (0xa1, 0xfe))
    gbk_han = {c for c in legacy('gbk', (0x81, 0xfe), (0x40, 0xff)) if 0x4e00 <= c <= 0x9fff} - gb2312
    return [
        COMMON | rng((0x100, 0x24f), (0x370, 0x3ff), (0x400, 0x4ff), (0x20a0, 0x20cf), (0x2100, 0x22ff), (0x2300, 0x23ff),
                     (0x2460, 0x27bf), (0x3040, 0x30ff), (0x31f0, 0x31ff)) | legacy('cp932', (0x81, 0xfc), (0x40, 0xfd)),
        COMMON | gb2312,
        COMMON | gbk_han,
        COMMON | legacy('big5', (0xa1, 0xf9), (0x40, 0xff)),
        COMMON | rng((0x1100, 0x11ff), (0x3130, 0x318f), (0xac00, 0xd7a3)) | legacy('euc_kr', (0xa1, 0xfe)),
    ]


def runs(codes):
    out = []
    for c in sorted(codes):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return ['%04x' % a if a == b else '%04x-%04x' % (a, b) for a, b in out]


def wrap(words, width=100):
    lines, cur = [], ''
    for w in words:
        if cur and len(cur) + 1 + len(w) > width:
            lines.append(cur)
            cur = w
        else:
            cur = cur + ' ' + w if cur else w
    if cur:
        lines.append(cur)
    return lines


def main(path):
    sets = charsets()
    every = set().union(*sets)
    out = ['# The character sets of the shared font stand-ins, types 0 to 4 (generated by tools/gen_font_charsets.py, do not edit).',
           '# "type N": hex code points and ranges. "mirror": a character and its bidi mirror.',
           '# "os2": the start, end and ulUnicodeRange bit of each Unicode block, sorted by start.']
    for t, s in enumerate(sets):
        out.append('type %d' % t)
        out += wrap(runs(s))
    out.append('mirror')
    out += wrap(['%04x:%04x' % (c, m) for c in sorted(every) for m in [mirrored(c)] if m is not None])
    out.append('os2')
    blocks = sorted((a, b, bit) for bit, bs in enumerate(OS2_UNICODE_RANGES) for _, (a, b) in bs)
    out += ['%04x-%04x %d' % b for b in blocks]
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
