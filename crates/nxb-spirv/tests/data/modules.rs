#[allow(dead_code)]
const fn spirv_bytes<const N: usize>(words: &[u32]) -> [u8; N] {
    let mut out = [0u8; N];
    let mut i = 0;
    while i < words.len() {
        let b = words[i].to_le_bytes();
        out[4 * i] = b[0];
        out[4 * i + 1] = b[1];
        out[4 * i + 2] = b[2];
        out[4 * i + 3] = b[3];
        i += 1;
    }
    out
}

